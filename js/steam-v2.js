function normalizeWordsForEvaluation(text) {
  return text.toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zñáéíóúü0-9\s]/gi, ' ')
    .split(/\s+/)
    .filter(Boolean);
}

function isIncoherentWriting(text, words, topicHits, hasVerb) {
  const clean = text.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const lettersOnly = clean.replace(/[^a-zñ]/g, '');
  const vowels = (lettersOnly.match(/[aeiou]/g) || []).length;
  const vowelRatio = lettersOnly.length ? vowels / lettersOnly.length : 0;
  const longestWord = words.reduce((max, word) => Math.max(max, word.length), 0);
  const commonSpanishWords = words.filter(word => /^(el|la|los|las|un|una|es|son|de|del|que|para|con|tiene|sirve|agua|sol|luz|casa|color|mouse|numero)$/i.test(word)).length;
  const consonantStreak = /[bcdfghjklmnñpqrstvwxyz]{5,}/i.test(lettersOnly);
  const repeatedCharacters = /(.)\1{4,}/.test(clean);
  const oneLongUnknownWord = words.length <= 2 && longestWord >= 14 && topicHits === 0 && !hasVerb;
  const strangeVowelBalance = lettersOnly.length >= 14 && (vowelRatio < 0.22 || vowelRatio > 0.78);
  return repeatedCharacters || consonantStreak || oneLongUnknownWord || (strangeVowelBalance && commonSpanishWords === 0 && topicHits === 0);
}

function evaluateWritingAnswer(text, key) {
  const content = getRichModeContent(key);
  const words = normalizeWordsForEvaluation(text);
  const unique = new Set(words);
  const topicWords = normalizeWordsForEvaluation(`${content.topic} ${content.definition} ${content.reading}`).filter(w => w.length > 3);
  const topicHits = [...new Set(topicWords)].filter(w => unique.has(w)).length;
  const repeatedRatio = words.length ? unique.size / words.length : 0;
  const hasVerb = /\b(es|son|sirve|ayuda|tiene|necesita|puede|usa|mueve|cuida|crece|suma|resta|compara|expresa)\b/i.test(text);
  const incoherent = isIncoherentWriting(text, words, topicHits, hasVerb);
  const gibberish = incoherent || repeatedRatio < 0.35;
  if (incoherent) {
    return {
      score: 0,
      nivel: 'En desarrollo',
      feedback: 'No pude entender la respuesta. Escribí una frase real sobre la actividad para poder evaluarla.',
      siguiente_paso: 'Volvé a mirar el contenido y respondé con tus propias palabras.'
    };
  }
  let score = 0;
  if (text.trim().length >= 10) score += 2;
  if (words.length >= 6) score += 2;
  if (words.length >= 12) score += 1;
  if (topicHits >= 1) score += 2;
  if (topicHits >= 2) score += 1;
  if (hasVerb) score += 1;
  if (/[.!?]/.test(text) || words.length >= 10) score += 1;
  if (gibberish) score = Math.min(score, 3);
  score = Math.max(1, Math.min(10, score));
  const nivel = score >= 8 ? 'Muy bueno' : score >= 5 ? 'Bueno' : 'En desarrollo';
  const feedback = score >= 8
    ? 'Muy buen trabajo. La respuesta se relaciona con el tema y explica una idea clara.'
    : score >= 5
      ? 'Vas bien. Hay una idea relacionada, pero podés agregar una explicación más completa.'
      : 'Todavía falta conectar mejor la respuesta con el tema. Probá nombrar qué es y para qué sirve o qué pasa.';
  const siguiente_paso = score >= 8 ? 'Podés avanzar al siguiente subnivel.' : 'Revisá la actividad una vez más y agregá una frase con tus propias palabras.';
  return { score, nivel, feedback, siguiente_paso };
}

submitWriting = async function(key) {
  const textarea = document.getElementById('writing-input');
  const feedbackBox = document.getElementById('writing-feedback');
  const btn = document.getElementById('submit-writing-btn');
  const text = textarea?.value?.trim() || '';
  if (!feedbackBox || !btn) return;
  if (text.length < 10) {
    feedbackBox.className = 'feedback-box feedback-result error-result';
    feedbackBox.innerHTML = 'Escribí al menos una frase corta sobre lo que entendiste.';
    return;
  }
  btn.disabled = true;
  feedbackBox.className = 'feedback-box feedback-result';
  feedbackBox.innerHTML = '<span class="loading-spinner"></span> Analizando tu respuesta...';
  setTimeout(() => {
    const result = evaluateWritingAnswer(text, key);
    feedbackBox.innerHTML = `
      <div style="font-size:28px;margin-bottom:8px">🧠 ${result.nivel}</div>
      <p style="margin-bottom:6px"><strong>Puntaje: ${result.score}/10</strong></p>
      <p style="margin-bottom:6px">💬 <strong>Feedback:</strong> ${result.feedback}</p>
      <p style="margin-bottom:6px">➡️ <strong>Siguiente paso:</strong> ${result.siguiente_paso}</p>
    `;
    btn.textContent = `✓ Evaluado: ${result.score}/10`;
    btn.disabled = false;
    if (result.score >= 5) {
      markActivityReviewed(key, 'reading', 'Respuesta revisada. Ya podés completar.');
    } else {
      showToast('Mejorá un poco la respuesta antes de completar.', 'error');
    }
  }, 900);
};

